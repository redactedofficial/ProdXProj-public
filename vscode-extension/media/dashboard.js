'use strict';
const api = acquireVsCodeApi();
const byId = id => document.getElementById(id);
let plan;
function send(action) {
  api.postMessage({action, replicas: Number(byId('replicas').value), target: byId('target').value,
    options: Object.fromEntries(['env', 'keys', 'data', 'secrets'].map(x => [x, byId(x).checked]))});
}
document.querySelectorAll('[data-action]').forEach(button => button.addEventListener('click', () => send(button.dataset.action)));
['env', 'keys', 'data', 'secrets', 'target'].forEach(id => byId(id).addEventListener('change', () => send('options')));
function node(tag, text) {const element = document.createElement(tag); if (text !== undefined) element.textContent = String(text); return element;}
function rows(id, values) {
  byId(id).replaceChildren(...values.map(values => {const row = node('tr'); row.append(...values.map(x => {
    const cell = node('td'); if (x instanceof HTMLElement) cell.append(x); else cell.textContent = String(x ?? ''); return cell;
  })); return row;}));
}
function files() {
  if (!plan) return;
  const query = byId('filter').value.toLowerCase();
  const selected = plan.files.filter(x => `${x.source} ${x.package} ${x.destination}`.toLowerCase().includes(query));
  rows('files', selected.slice(0, 2000).map(x => {
    let source = x.source;
    if (source !== 'Generated by ProdXProj' && plan.files.some(y => y.source === source) && !source.startsWith('Rendered ') && !source.startsWith('Configured ')) {
      source = node('button', x.source); source.addEventListener('click', () => api.postMessage({action:'open-file', path:x.source}));
    }
    return [source, x.package, x.destination, `${x.action}. ${x.checked}`];
  }));
  byId('file-count').textContent = `${selected.length} matching files; displaying up to 2,000. Filter to inspect others.`;
}
byId('filter').addEventListener('input', files);
window.addEventListener('message', event => {
  const message = event.data;
  if (message.type === 'error') {byId('status').textContent = message.value; return;}
  if (message.type === 'busy') {
    document.querySelectorAll('button,input,select').forEach(x => {x.disabled = message.value;});
    byId('status').textContent = message.value ? 'Operation running…' : 'Operation finished.';
    return;
  }
  if (message.type === 'result') {byId('result').textContent = JSON.stringify(message.value, null, 2); return;}
  if (message.type !== 'plan') return;
  plan = message.value;
  byId('summary').textContent = `${plan.project} · version ${plan.version} · ${plan.root} · Startup: ${plan.startup}`;
  byId('status').textContent = plan.mode;
  const target = byId('target');
  target.replaceChildren(node('option', 'Select target')); target.firstChild.value = '';
  for (const name of plan.targets) {const option = node('option', name); option.value = name; target.append(option);}
  target.value = message.selectedTarget || '';
  byId('phases').replaceChildren(...plan.phases.map(x => {
    const details = node('details'); details.append(node('summary', `${x.name} · ${x.location}`), node('p', x.effect));
    if (x.commands?.length) details.append(node('pre', JSON.stringify(x.commands, null, 2)));
    return details;
  }));
  byId('issues').replaceChildren(...plan.issues.map(x => node('li', x)));
  rows('variables', plan.variables.map(x => [x.name, x.value, x.source, x.behavior]));
  files();
  byId('generated').replaceChildren(...Object.entries(plan.generated).map(([name, text]) => {
    const details = node('details'); details.append(node('summary', name), node('pre', text)); return details;
  }));
  byId('history').replaceChildren(...plan.history.map(x => {
    const details = node('details'); details.append(node('summary', `${x.version} · ${x.branch} · ${x.created} · ${x.id}`),
      node('pre', JSON.stringify({parents: x.parents || (x.parent ? [x.parent] : []), changes: x.changes, creator: x.creator, message: x.message}, null, 2)));
    return details;
  }));
  topology(plan.history);
});
function topology(history) {
  const ns = 'http://www.w3.org/2000/svg';
  const make = (tag, attrs) => {const x = document.createElementNS(ns, tag); for (const [k,v] of Object.entries(attrs)) x.setAttribute(k,String(v)); return x;};
  const nodes = history.slice(-1000), lanes = new Map(), positions = new Map();
  const svg = make('svg', {role:'img', 'aria-label':'Release branches and parent connections', width:800, height:Math.max(64,nodes.length*52+24)});
  const title = make('title', {}); title.textContent = 'Release topology; details and full history follow below.'; svg.append(title);
  nodes.forEach((release,i) => {
    const branch = release.branch || 'main'; if (!lanes.has(branch)) lanes.set(branch,lanes.size);
    positions.set(release.id,{x:24+lanes.get(branch)*28,y:28+i*52});
  });
  nodes.forEach(release => {
    const p = positions.get(release.id);
    for (const id of release.parents || (release.parent ? [release.parent] : [])) {
      const from = positions.get(id); if (from) svg.append(make('path',{d:`M${from.x} ${from.y} C${from.x} ${p.y-24},${p.x} ${p.y-24},${p.x} ${p.y}`,fill:'none',stroke:'currentColor'}));
    }
    svg.append(make('circle',{cx:p.x,cy:p.y,r:5,fill:'currentColor'}));
    const text = make('text',{x:24+lanes.size*28,y:p.y+4,fill:'currentColor'});
    text.textContent = `${release.version} · ${release.branch} · ${release.created}`; svg.append(text);
  });
  byId('topology').replaceChildren(svg);
}
send('ready');
