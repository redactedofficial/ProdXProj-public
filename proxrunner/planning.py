def variables(root, cfg, target_name=None, reveal=False):
    result = []
    for name, value in cfg.get("parameters", {}).items():
        result.append({"name": name, "value": value if reveal else "[set]", "source": "project parameters", "state": "set", "behavior": "Exported to runtime hooks/service"})
    for filename in cfg.get("env_files", []):
        path = (Path(root) / filename).resolve()
        if not path.is_relative_to(Path(root).resolve()) or not path.is_file() or path.stat().st_size > 1024**2:
            result.append({"name": filename, "value": "", "source": "environment file", "state": "missing / unreadable", "behavior": "Select a readable file"})
            continue
        for line in path.read_text(encoding="utf-8", errors="replace").splitlines():
            match = re.match(r"\s*(?:export\s+)?([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*)", line)
            if match:
                name, value = match.groups()
                result.append({"name": name, "value": value if reveal else "[set]" if value else "[empty]",
                               "source": filename, "state": "set" if value else "empty", "behavior": "File value; application/Compose loads it (no expansion performed here)"})
    target = cfg.get("targets", {}).get(target_name, {})
    base = target.get("root", "<deployment-root>")
    for name, value in (("PROX_RELEASE_ROOT", base + "/current"), ("PROX_DATA_ROOT", base + "/shared"), ("PROX_DEPLOY_ROOT", base)):
        result.append({"name": name, "value": value, "source": "ProdXProj runtime", "state": "planned", "behavior": "Set by the runner; hooks receive their immutable release path"})
    return result


def shipping_plan(root, cfg, options=None, target_name=None, release_id="<new-release-uuid>", output=None):
    root, cfg = Path(root).resolve(), validate(cfg)
    options = options or Inclusion()
    target = cfg.get("targets", {}).get(target_name, {})
    base = target.get("root", "<deployment-root>")
    generated = set(GENERATED) | set(package_documents(cfg))
    generated -= {"scripts/PRODX-runtime.py", "scripts/PRODX-systemd.service.in", "docs/PRODX-DOCKER.md"}
    generated |= set(package_documents(cfg))
    rows, issues, scripts, destinations = [], [], [], set()
    for source, package in iter_payload_files(root, cfg, options, output):
        runtime = runtime_destination(package)
        destination = (base + "/shared/" + runtime[5:]) if runtime and runtime.startswith("data/") else (base + "/releases/" + release_id + "/" + runtime[4:]) if runtime else "Client-side attachment only"
        action = "Seed only if absent; abort on existing top-level shared entry" if package.startswith("data/") else "Install immutable release file" if runtime else "Retain in encrypted package; no runtime upload"
        if runtime and destination in destinations:
            issues.append("Runtime destination collision: " + destination)
        destinations.add(destination) if runtime else None
        row = {"source": source.relative_to(root).as_posix(), "package": package, "destination": destination,
               "action": action, "bytes": source.stat().st_size, "checked": "SHA-256 and archive path checks during packaging/opening"}
        rows.append(row)
        if package.startswith("scripts/") or source.suffix in (".py", ".sh", ".ps1", ".js", ".ts"):
            scripts.append({"path": row["source"], "action": "Existing source; copied, never rewritten automatically"})
        if len(rows) > 100000:
            raise ValueError("Preview exceeds package file limit")
    for path in sorted(generated):
        runtime = runtime_destination(path)
        destination = base + "/releases/" + release_id + "/" + runtime[4:] if runtime else "Package metadata only"
        rows.append({"source": "Generated by ProdXProj", "package": path, "destination": destination,
                     "action": "Create package document/helper", "bytes": None, "checked": "Integrity checked with all package entries"})
        if path.startswith("scripts/"):
            scripts.append({"path": path, "action": "Generated runner/service description"})
    for name in (cfg.get("env_files", []) if options.env else []) + (cfg.get("data_paths", []) if options.data else []):
        if not (root / name).exists() and not options.all:
            issues.append("Selected path missing: " + name)
    if options.keys:
        for name, definition in cfg.get("targets", {}).items():
            if definition.get("key_file") and not (root / definition["key_file"]).is_file():
                issues.append("SSH identity missing for target " + name)
    if not cfg.get("service") and (not cfg.get("activate") or not cfg.get("health")):
        issues.append("Deployment needs managed service settings or activation and health commands")
    svc = cfg.get("service")
    if svc:
        if svc["type"] == "systemd":
            from .service_runtime import service_name
            unit_path = "/etc/systemd/system/" if svc.get("scope", "user") == "system" else "<remote-user-home>/.config/systemd/user/"
            rows.extend([{"source": "Rendered systemd template", "package": "scripts/PRODX-systemd.service.in", "destination": unit_path + service_name(cfg) + ".service", "action": "Create/update managed unit; preserve previous unit; validate ownership", "bytes": None, "checked": "systemctl daemon-reload, restart, is-active"},
                         {"source": "Configured runtime parameters", "package": "Protected runtime configuration", "destination": base + "/service/environment", "action": "Write protected environment file (0600)", "bytes": None, "checked": "Single-line environment values"}])
            if svc.get("scope", "user") == "user" and svc.get("run_on_start", True):
                issues.append("Boot startup requires loginctl linger on the target; not checked locally")
        else:
            rows.append({"source": "Compose services on server", "package": "Generated at activation", "destination": base + "/service/compose.override.json", "action": "Create project-scoped restart-policy override", "bytes": None, "checked": "docker compose config and up --wait"})
    phases = [{"name": "Build", "location": "client", "commands": cfg.get("build", []), "effect": "Run only for Compile; outputs can change the file inventory"},
              {"name": "Package", "location": "client", "effect": "Collect selected files; generate docs/scripts; encrypt when needed"},
              {"name": "Verify", "location": "client", "effect": "Verify artifact trust, paths, file hashes and encryption"},
              {"name": "Backup", "location": "server", "effect": "Quiesce previous release and snapshot active files/shared data/service settings"},
              {"name": "Stage", "location": "server", "effect": "Create release directory, seed absent data, journal current-pointer change"},
              {"name": "Activate", "location": "server", "commands": cfg.get("activate", []), "service": svc, "effect": "Apply managed service, activation and new-release resume hooks"},
              {"name": "Health", "location": "server", "commands": cfg.get("health", []), "effect": "Check service/app health; restore previous release on failure"},
              {"name": "Report", "location": "monitor", "effect": "Installed reporter sends observed status; requires remote setup"}]
    return {"project": cfg["name"], "version": cfg["version"], "target": target_name, "host": target.get("host"),
            "root": base, "mode": "Local, read-only plan; remote filesystem/privileges are not checked", "files": rows,
            "scripts": scripts, "phases": phases, "issues": issues, "generated": package_documents(cfg),
            "startup": svc.get("run_on_start", True) if svc else "Defined by custom hooks", "user_data": cfg.get("data_paths", [])}


def check_script(path, text=None):
    path = Path(path)
    text = path.read_text(encoding="utf-8") if text is None else text
    effects = []
    for label, pattern in (("Service management", r"systemctl|service\s"), ("Container management", r"docker|podman"),
                           ("Package installation", r"apt-get|dnf|apk|pip install|npm install"),
                           ("Filesystem writes/deletion", r"write_text|write_bytes|unlink|rmtree|\brm\b|\bmkdir\b"),
                           ("Network/process execution", r"subprocess|requests\.|urlopen|\bcurl\b|\bssh\b")):
        if re.search(pattern, text):
            effects.append(label)
    result = {"path": str(path), "effects": effects, "executed": False,
              "note": "Static indicators only; arbitrary script side effects require code review"}
    if path.suffix == ".py":
        try:
            ast.parse(text)
            result.update(valid=True, checker="Python AST", diagnostics=[])
        except SyntaxError as error:
            result.update(valid=False, checker="Python AST", diagnostics=[{"line": error.lineno, "message": error.msg}])
    elif path.suffix == ".json":
        try:
            json.loads(text)
            result.update(valid=True, checker="JSON parser", diagnostics=[])
        except json.JSONDecodeError as error:
            result.update(valid=False, checker="JSON parser", diagnostics=[{"line": error.lineno, "message": error.msg}])
    elif path.suffix == ".sh" and shutil.which("sh"):
        checked = subprocess.run(["sh", "-n"], input=text.encode(), capture_output=True, timeout=10)
        result.update(valid=checked.returncode == 0, checker="sh -n", diagnostics=[] if checked.returncode == 0 else [{"message": "Shell syntax check failed"}])
    else:
        result.update(valid=None, checker="No local syntax checker available", diagnostics=[])
    return result
